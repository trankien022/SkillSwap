/**
 * Generates the API reference under `docs/api/` from the live OpenAPI document.
 *
 *   node scripts/gen-api-docs.cjs
 *
 * Boots the real AppModule (so every @ApiOperation/@ApiParam is reflected), pulls
 * the sorted document from `apps/api/dist/bootstrap/openapi.js`, and writes one
 * page per module tag plus an index. Requires `pnpm build` and a reachable DB
 * (the app initialises its data sources on boot).
 *
 * CommonJS on purpose: the compiled api is CJS and Nest's DI metadata must live in
 * the same module realm as `@nestjs/core`, or boot dies silently.
 */

