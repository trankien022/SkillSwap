const HTTP_METHODS = ['get', 'post', 'put', 'patch', 'delete', 'head', 'options'];

function loadRootEnv() {
  const envPath = join(ROOT, '.env');
  if (!existsSync(envPath)) return;
  for (const line of readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const match = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/.exec(line);
    if (!match) continue;
    let value = match[2];
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    } else {
      value = value.replace(/\s+#.*$/, '').trim();
    }
    if (process.env[match[1]] === undefined && value !== '') {
      process.env[match[1]] = value;
    }
  }
}

/** Collects every operation, grouped by its first tag. */
function collectOperations(doc) {
  const byTag = new Map();
  for (const [path, item] of Object.entries(doc.paths || {})) {
    for (const [method, op] of Object.entries(item || {})) {
      if (!HTTP_METHODS.includes(method)) continue;
      const tag = (op.tags && op.tags[0]) || 'untagged';
      if (!byTag.has(tag)) byTag.set(tag, []);
      byTag.get(tag).push({ method, path, op });
    }
  }
  return byTag;
}

function refName(schema) {
  if (!schema) return null;
  if (schema.$ref) return schema.$ref.split('/').pop();
  if (schema.type === 'array') {
    const inner = refName(schema.items);
    return inner ? `${inner}[]` : 'array';
  }
  if (schema.anyOf && schema.anyOf.length) {
    return schema.anyOf.map(refName).filter(Boolean).join(' | ') || null;
  }
  return schema.type || null;
}

function bodySchema(op) {
  const content = op.requestBody && op.requestBody.content;
  if (!content) return null;
  const media = content['application/json'] || Object.values(content)[0];
  return (media && media.schema) || null;
}

function responseSchema(op) {
  for (const code of ['200', '201', '202', '204']) {
    const resp = op.responses && op.responses[code];
    if (!resp) continue;
    const schema = resp.content && resp.content['application/json'] && resp.content['application/json'].schema;
    if (schema) return refName(schema);
    return code === '204' ? 'no content' : null;
  }
  return null;
}

function paramsTable(op) {
  const params = (op.parameters || []).filter((p) => p.in !== 'header');
  const headers = (op.parameters || []).filter((p) => p.in === 'header');
  const lines = [];
  if (params.length) {
    lines.push('| Param | In | Type | Required | Description |', '|---|---|---|---|---|');
    for (const p of params) {
      lines.push(
        `| \`${p.name}\` | ${p.in} | ${refName(p.schema) || 'string'} | ${p.required ? 'yes' : 'no'} | ${p.description || ''} |`,
      );
    }
  }
  if (headers.length) {
    if (lines.length) lines.push('');
    lines.push('**Headers**', '', '| Header | Required | Description |', '|---|---|---|');
    for (const h of headers) {
      lines.push(`| \`${h.name}\` | ${h.required ? 'yes' : 'no'} | ${h.description || ''} |`);
    }
  }
  return lines.join('\n');
}

function renderOperation(tag, { method, path, op }) {
  const notes = MODULE_NOTES[tag] && MODULE_NOTES[tag].endpoints[`${method.toUpperCase()} ${path}`];
  const auth = (op.security || []).length ? '🔒 Bearer token required' : 'Public';
  const out = [];
  out.push(`### \`${method.toUpperCase()} ${path}\``);
  out.push('');
  out.push(`**${op.summary || '(no summary)'}**`);
  out.push('');
  if (notes) {
    out.push(notes);
    out.push('');
  }
  out.push(`- Auth: ${auth}`);
  const reqBody = refName(bodySchema(op));
  const resBody = responseSchema(op);
  if (reqBody) out.push(`- Request body: \`${reqBody}\``);
  if (resBody) out.push(`- Response: \`${resBody}\``);
  out.push('');
  const params = paramsTable(op);
  if (params) {
    out.push(params);
    out.push('');
  }
  return out.join('\n');
}

function renderModule(tag, operations) {
  const notes = MODULE_NOTES[tag] || { purpose: '', endpoints: {} };
  const out = [];
  out.push(`# ${tag}`);
  out.push('');
  out.push(`> ${BANNER} — do not edit by hand. See [the index](./index.md).`);
  out.push('');
  if (notes.purpose) {
    out.push('## What it is for');
    out.push('');
    out.push(notes.purpose);
    out.push('');
  }
  out.push(`${operations.length} endpoint${operations.length === 1 ? '' : 's'}.`);
  out.push('');
  for (const operation of operations) {
    out.push(renderOperation(tag, operation));
  }
  return out.join('\n');
}

function renderIndex(byTag) {
  const out = [];
  out.push('# API reference');
  out.push('');
  out.push(`> ${BANNER} from the live OpenAPI document — do not edit by hand.`);
  out.push('');
  out.push('Live, interactive spec: **`/api/docs`** (Swagger UI) · `/api/docs-json` (raw OpenAPI).');
  out.push('For the guided booking flow, see [FRONTEND-API-GUIDE.md](./FRONTEND-API-GUIDE.md).');
  out.push('');
  out.push('All routes are prefixed with `/api`. Authenticated routes need `Authorization: Bearer <accessToken>`.');
  out.push('');
  out.push('| Module | Endpoints | What it is for |');
  out.push('|---|---|---|');
  for (const [tag, operations] of [...byTag.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
    const purpose = (MODULE_NOTES[tag] && MODULE_NOTES[tag].purpose) || '';
    out.push(`| [${tag}](./${tag}.md) | ${operations.length} | ${purpose.split('. ')[0]} |`);
  }
  out.push('');
  return out.join('\n');
}

async function main() {
  // The api resolves some config (e.g. JWT key paths) relative to its own cwd,
  // and boots cleanly only from apps/api. Load the root .env by absolute path,
  // then run the app from its own directory.
  loadRootEnv();
  process.chdir(join(ROOT, 'apps', 'api'));
  const { NestFactory } = require('@nestjs/core');
  const { AppModule } = require(join(ROOT, 'apps', 'api', 'dist', 'bootstrap', 'app.module.js'));
  const { buildOpenApiDocument } = require(join(ROOT, 'apps', 'api', 'dist', 'bootstrap', 'openapi.js'));

  const app = await NestFactory.create(AppModule, { logger: false });
  app.setGlobalPrefix('api');
  const doc = buildOpenApiDocument(app);
  await app.close();

  const byTag = collectOperations(doc);

  mkdirSync(OUT_DIR, { recursive: true });
  // Remove only previously generated pages, never hand-written files.
  for (const file of readdirSync(OUT_DIR)) {
    if (!file.endsWith('.md')) continue;
    const full = join(OUT_DIR, file);
    if (readFileSync(full, 'utf8').slice(0, 200).includes(BANNER)) {
      rmSync(full, { force: true });
    }
  }

  for (const [tag, operations] of byTag.entries()) {
    writeFileSync(join(OUT_DIR, `${tag}.md`), renderModule(tag, operations), 'utf8');
  }
  writeFileSync(join(OUT_DIR, 'index.md'), renderIndex(byTag), 'utf8');

  console.log(`docs:api wrote ${byTag.size} module pages + index to docs/api/`);
}

main().then(
  () => process.exit(0),
  (error) => {
    console.error(error);
    process.exit(1);
  },
);
